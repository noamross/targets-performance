# Profile selected targets with Rprof, one profile file per target (and branch),
# without touching the real store or project outputs.
# Usage (from the project root):
#   Rscript profile_pipeline.R out=<dir outside project> [script=_targets.R] [store=_targets]
#                              [names=a,b | top=10] [memory=TRUE] [interval=0.02]
# How: copies the store to <out>/store, writes <out>/_targets_profile.R, which
# sources the project script and wraps the chosen targets' commands with
# tarchetypes::tar_hook_outer(), then runs tar_make() on the copy. Wrapped
# targets rerun (their commands changed); downstream targets rerun only if a
# wrapped target returns a different value, so deterministic pipelines rebuild
# nothing else. File, URL and *_deployed targets are never wrapped.
# This RUNS pipeline code: get the user's approval first, and check for
# side-effecting targets (deploys, uploads, writes outside the store).
# Then summarise with: Rscript profile_summary.R <out>/profiles

args <- commandArgs(trailingOnly = TRUE)
kv <- function(key, default) {
  hit <- grep(paste0("^", key, "="), args, value = TRUE)
  if (length(hit)) sub("^[^=]+=", "", hit[[1]]) else default
}
out <- kv("out", NA)
if (is.na(out)) stop("give out=<directory outside the project>")
script <- normalizePath(kv("script", "_targets.R"))
store <- normalizePath(kv("store", "_targets"))
top <- as.integer(kv("top", "10"))
memory <- toupper(kv("memory", "TRUE")) == "TRUE"
interval <- as.numeric(kv("interval", "0.02"))
out <- normalizePath(out, mustWork = FALSE)
if (startsWith(out, normalizePath(getwd()))) stop("out= must be outside the project directory")
dir.create(out, recursive = TRUE, showWarnings = FALSE)

meta <- targets::tar_meta(store = store, fields = c("name", "type", "format", "seconds"))
man <- targets::tar_manifest(script = script, fields = c("name", "format"))
excluded <- man$name[man$format %in% c("file", "file_fast", "url", "aws_file") | grepl("_deployed$", man$name)]
names_arg <- kv("names", NA)
chosen <- if (!is.na(names_arg)) {
  strsplit(names_arg, ",")[[1]]
} else {
  stems <- meta[meta$type %in% c("stem", "pattern") & meta$name %in% man$name & !meta$name %in% excluded, ]
  utils::head(stems$name[order(-stems$seconds)], top)
}
skipped <- intersect(chosen, excluded)
chosen <- setdiff(chosen, excluded)
if (length(skipped)) cat("not wrapped (file/url/deploy):", paste(skipped, collapse = ", "), "\n")
if (!length(chosen)) stop("no targets to profile")
est <- sum(meta$seconds[meta$name %in% chosen], na.rm = TRUE)
secs <- function(x) if (x < 1) sprintf("%.0f ms", 1e3 * x) else sprintf("%.1f s", x)
cat(sprintf("profiling %d targets; last build took %s for them (expect a little more with profiling)\n",
            length(chosen), secs(est)))
cat("  downstream targets also rerun if a wrapped target returns a different value (non-deterministic\n",
    "  code); their side effects (files written relative to the project) then run too.\n", sep = "")

copy <- file.path(out, "store")
unlink(copy, recursive = TRUE)
dir.create(copy)
invisible(file.copy(list.files(store, full.names = TRUE, all.files = TRUE, no.. = TRUE), copy, recursive = TRUE))
prof_dir <- file.path(out, "profiles")
dir.create(prof_dir, showWarnings = FALSE)

wrapper <- file.path(out, "_targets_profile.R")
writeLines(c(
  "# Generated by profile_pipeline.R; safe to delete.",
  sprintf("pipeline <- source(%s, local = TRUE)$value", deparse(script)),
  "profile_target <- function(value, name = targets::tar_name(),",
  sprintf("                           dir = %s) {", deparse(prof_dir)),
  sprintf("  utils::Rprof(file.path(dir, paste0(name, '.Rprof')), interval = %s, memory.profiling = %s)", interval, memory),
  "  on.exit(utils::Rprof(NULL), add = TRUE)",
  "  value",
  "}",
  sprintf("tarchetypes::tar_hook_outer(pipeline, hook = profile_target(.x), names = tidyselect::any_of(%s))",
          paste(deparse(chosen), collapse = ""))
), wrapper)

# tar_make() captures names= unevaluated, so splice the names in as a literal.
make <- bquote(targets::tar_make(script = .(wrapper), store = .(copy), names = tidyselect::any_of(.(chosen))))
t <- system.time(eval(make))[["elapsed"]]
cat(sprintf("done in %s; %d profiles in %s\n", secs(t), length(list.files(prof_dir)), prof_dir))
cat("next: Rscript profile_summary.R", prof_dir, "\n")
